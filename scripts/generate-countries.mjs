// Generates src/domain/geo/countries.generated.ts from libphonenumber-js metadata
// and the ICU display names bundled with Node. Run: node scripts/generate-countries.mjs
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/min';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const metadata = JSON.parse(readFileSync(createRequire(import.meta.url).resolve('libphonenumber-js/metadata.min.json'), 'utf8'));

const en = new Intl.DisplayNames(['en'], { type: 'region' });
const tr = new Intl.DisplayNames(['tr'], { type: 'region' });
const rows = getCountries()
  .map((code) => ({ code, name: en.of(code), nameTr: tr.of(code), callingCode: getCountryCallingCode(code), primary: metadata.country_calling_codes[getCountryCallingCode(code)][0] === code }))
  .filter((c) => c.name && c.name !== c.code)
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));
// Use the country's own preferred English name.
for (const r of rows) if (r.code === 'TR') r.name = 'Türkiye';
const body = rows.map((r) => `  { code: '${r.code}', name: ${JSON.stringify(r.name)}, nameTr: ${JSON.stringify(r.nameTr)}, callingCode: '${r.callingCode}'${r.primary ? ', primaryForCallingCode: true' : ''} },`).join('\n');
writeFileSync('src/domain/geo/countries.generated.ts', `// GENERATED by scripts/generate-countries.mjs — do not edit by hand.\nimport type { Country } from '../models';\n\nexport const COUNTRIES_GENERATED: readonly Country[] = [\n${body}\n];\n`);
console.log(rows.length, 'countries');
